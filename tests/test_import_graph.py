"""Tests: Import graph of src/bioage and the rules it must keep.

- docs/import_graph.md matches the imports in the code (after a change: write_graph() and review the diff)
- Nothing outside app/ imports from it: the app pulls from the rest, not the other way round
- config/ imports nothing from the rest of the project
"""

# Imports
import ast

from bioage.config.paths import ROOT

PACKAGE = ROOT / "src" / "bioage"
GRAPH = ROOT / "docs" / "import_graph.md"


def project_imports() -> dict[str, set[str]]:
    """Module → project modules it imports, with config/ as a single node."""
    imports = {}
    for path in sorted(PACKAGE.rglob("*.py")):
        if path.name == "__init__.py":
            continue
        module = node_name(".".join(path.relative_to(PACKAGE).with_suffix("").parts))
        found = imports.setdefault(module, set())
        for statement in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(statement, ast.ImportFrom) and (statement.module or "").startswith("bioage."):
                names = [statement.module.removeprefix("bioage.")]
                if "." not in names[0]:  # from bioage.app import predict
                    names = [f"{names[0]}.{alias.name}" for alias in statement.names]
                found |= {node_name(name) for name in names} - {module}
    return imports


def node_name(module: str) -> str:
    """Graph node of a module: every config file is one node."""
    return "config" if module.startswith("config") else module


def mermaid() -> str:
    """Import graph as a Mermaid diagram, one box per folder."""
    imports = project_imports()
    lines = [
        "# Import graph",
        "",
        "Which module of `src/bioage` imports which. Almost every module also reads `config/` (arrows left out).",
        "Generated by `write_graph()` in `tests/test_import_graph.py`.",
        "",
        "```mermaid",
        "flowchart LR",
    ]
    folders = sorted({module.split(".")[0] for module in imports if "." in module})
    for folder in folders:
        lines.append(f"  subgraph {folder}")
        lines += [f"    {node(m)}[{m.split('.')[1]}]" for m in sorted(imports) if m.startswith(folder + ".")]
        lines.append("  end")
    lines += [f"  {node(m)}[{m}]" for m in sorted(imports) if "." not in m and m != "config"]
    lines += [f"  {node(m)} --> {node(t)}" for m in sorted(imports) for t in sorted(imports[m] - {"config"})]
    lines.append("```")
    return "\n".join(lines) + "\n"


def node(module: str) -> str:
    """Mermaid id of a module."""
    return module.replace(".", "_")


def test_graph_up_to_date() -> None:
    assert GRAPH.read_text(encoding="utf-8") == mermaid(), "imports changed: run write_graph() and review the diff"


def test_nothing_imports_the_app() -> None:
    importers = {m for m, targets in project_imports().items() if any(t.startswith("app.") for t in targets)}
    assert {m for m in importers if not m.startswith("app.")} == set()


def test_config_imports_nothing_of_the_project() -> None:
    assert project_imports()["config"] == set()


def write_graph() -> None:
    """Current imports → GRAPH."""
    GRAPH.write_text(mermaid(), encoding="utf-8", newline="\n")
